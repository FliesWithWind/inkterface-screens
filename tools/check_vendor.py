#!/usr/bin/env python3
"""Verify the vendored copy of inkterface_core (vendor/inkterface_core/).

Runs with NO plugin repo: checks every vendored file against vendor/SHA256SUMS, that the files on disk
and the sums list match exactly (no extra, no missing), and that vendor/PLUGIN_COMMIT is a full 40-hex
sha. With --plugin <path> it ALSO checks each vendored file is byte-identical to `git show
<PLUGIN_COMMIT>:<plugin-path>` in that checkout, proving the copy really came from that commit.

Exit 0 and prints OK when clean; exit 1 and prints each problem otherwise. Used as a CI step before
validation and by tests/test_vendor.py.
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
VENDOR = REPO_ROOT / "vendor"
PKG = "inkterface_core"
PLUGIN_PKG_PREFIX = "decky/py_modules/inkterface_core"


def _parse_sums(text: str) -> dict[str, str]:
    sums: dict[str, str] = {}
    for line in text.splitlines():
        line = line.rstrip("\n")
        if not line.strip():
            continue
        # "<hex>  <path>" (two spaces, sha256sum format)
        h, _, p = line.partition("  ")
        if not p:
            raise ValueError(f"malformed SHA256SUMS line: {line!r}")
        sums[p] = h
    return sums


def check(plugin: Path | None = None) -> list[str]:
    """Return a list of problems; empty means the vendored copy is sound."""
    problems: list[str] = []

    commit_file = VENDOR / "PLUGIN_COMMIT"
    sums_file = VENDOR / "SHA256SUMS"
    pkg_dir = VENDOR / PKG

    if not commit_file.is_file():
        return [f"{commit_file}: missing"]
    if not sums_file.is_file():
        return [f"{sums_file}: missing"]
    if not pkg_dir.is_dir():
        return [f"{pkg_dir}: missing"]

    commit = commit_file.read_text("utf-8").strip()
    if len(commit) != 40 or any(c not in "0123456789abcdef" for c in commit):
        problems.append(f"PLUGIN_COMMIT: not a full 40-hex sha: {commit!r}")

    try:
        sums = _parse_sums(sums_file.read_text("utf-8"))
    except ValueError as e:
        return problems + [str(e)]

    expected = set(sums)
    # Every vendored file present under vendor/inkterface_core/ (as PKG/-relative posix paths), ignoring
    # Python's generated bytecode caches (gitignored, never vendored).
    present = {
        f"{PKG}/{p.relative_to(pkg_dir).as_posix()}"
        for p in pkg_dir.rglob("*")
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"
    }

    for extra in sorted(present - expected):
        problems.append(f"{extra}: present on disk but not in SHA256SUMS (extra file)")
    for missing in sorted(expected - present):
        problems.append(f"{missing}: in SHA256SUMS but missing on disk")

    for rel in sorted(expected & present):
        data = (VENDOR / rel).read_bytes()
        got = hashlib.sha256(data).hexdigest()
        if got != sums[rel]:
            problems.append(f"{rel}: sha256 {got} != recorded {sums[rel]} (tampered)")

    if plugin is not None and not problems:
        problems += _check_against_plugin(plugin, commit, sorted(expected & present))

    return problems


def _check_against_plugin(plugin: Path, commit: str, rels: list[str]) -> list[str]:
    problems: list[str] = []
    if not (plugin / ".git").exists():
        return [f"--plugin {plugin}: not a git checkout"]
    for rel in rels:
        plugin_path = f"{PLUGIN_PKG_PREFIX}/{rel[len(PKG) + 1:]}"
        try:
            upstream = subprocess.run(
                ["git", "-C", str(plugin), "show", f"{commit}:{plugin_path}"],
                check=True, capture_output=True,
            ).stdout
        except subprocess.CalledProcessError as e:
            problems.append(f"{rel}: git show {commit}:{plugin_path} failed: "
                            f"{e.stderr.decode('utf-8', 'replace').strip()}")
            continue
        if upstream != (VENDOR / rel).read_bytes():
            problems.append(f"{rel}: differs from {commit}:{plugin_path} in the plugin repo")
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Verify vendor/inkterface_core.")
    ap.add_argument("--plugin", type=Path, help="also verify each file against this plugin checkout at PLUGIN_COMMIT")
    args = ap.parse_args(argv)
    problems = check(args.plugin.expanduser().resolve() if args.plugin else None)
    if problems:
        print("vendor check FAILED:", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    print(f"vendor OK: {VENDOR / PKG} matches SHA256SUMS at PLUGIN_COMMIT "
          f"{(VENDOR / 'PLUGIN_COMMIT').read_text('utf-8').strip()[:12]}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
